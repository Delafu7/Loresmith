// Phase 1 ("Adapt the App"): every content entity gets a stable UUID id
// instead of a BIGSERIAL bigint. Generated from a live-schema introspection
// script (not hand-written) given the scale: 39 tables with a genuine
// surrogate `id` PK, 79 FK columns pointing at one of them, 5 composite-PK
// junction tables whose PK members are themselves FK columns
// (character_classes, character_saving_throw_proficiencies,
// character_skill_proficiencies, class_multiclass_prerequisites,
// rest_event_characters), 4 array-typed "soft FK" columns with no real
// constraint (backgrounds.skill_proficiency_ids, characters.languages,
// classes.saving_throw_proficiency_ids, monsters.condition_immunity_ids),
// 33 non-pkey indexes (9 of which are actually backed by a named UNIQUE
// table constraint, not a bare index — those need ALTER TABLE ... DROP/ADD
// CONSTRAINT, not DROP/CREATE INDEX) and 7 CHECK constraints that reference
// a promoted column and would otherwise silently reattach to the wrong
// (legacy) column on rename.
//
// Deliberately NOT touched: tables whose primary key is a natural key, not a
// surrogate id — srd_editions (PK=code), multiclass_spell_slot_table
// (PK=combined_caster_level) — and spell_classes, which has no PK at all
// (just a unique index over three FK columns). Their own FK columns that
// point at a converting table still get promoted to UUID; the natural-key
// tables' own PK stays exactly as it is.
//
// Strategy: expand-contract, not an in-place type change.
//   Phase A: every surrogate table gets a new `id_new UUID DEFAULT
//            gen_random_uuid()` column alongside its existing bigint `id`.
//   Phase B: every FK column gets a matching `<col>_new UUID` shadow column,
//            backfilled by joining to the referenced table's new id.
//   Phase C: constraints/indexes that reference a column about to be
//            renamed are dropped up front — a plain column rename doesn't
//            error, but it WOULD silently leave the old constraint/index
//            attached to the renamed-away legacy column instead of the new
//            one, which is wrong (e.g. `characters_check` verifying
//            `owner_user_id IS NOT NULL` needs to check the live column, not
//            a column nothing writes to anymore).
//   Phase D: promote — old column renamed to `<col>_legacy` (kept, not
//            dropped: if anything's wrong post-migration, the original
//            bigint data is still sitting right there to recover from),
//            `<col>_new` renamed to the ORIGINAL name. Downstream SQL/app
//            code needs no column-name changes, only type changes.
//   Phase E: FK constraints, composite PKs, CHECKs, and indexes recreated
//            against the now-promoted (UUID) columns.
//
// The `_legacy` bigint columns are intentionally left in place after this
// migration — a follow-up cleanup migration should drop them once the
// application is confirmed fully working end-to-end against UUIDs.

